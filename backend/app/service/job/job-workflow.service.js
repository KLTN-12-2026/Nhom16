const { ApiError } = require('../../util')

const JOB_STATUS = Object.freeze({ DRAFT: 'DRAFT', ACTIVE: 'ACTIVE', HIDDEN: 'HIDDEN', CLOSED: 'CLOSED', EXPIRED: 'EXPIRED' })
const APPLICATION_STATUS = Object.freeze({ RECEIVED: 'RECEIVED', REVIEWING: 'REVIEWING', INTERVIEW: 'INTERVIEW', OFFER: 'OFFER', REJECTED: 'REJECTED' })

const JOB_TRANSITIONS = Object.freeze({
  [JOB_STATUS.DRAFT]: [JOB_STATUS.ACTIVE, JOB_STATUS.CLOSED],
  [JOB_STATUS.ACTIVE]: [JOB_STATUS.HIDDEN, JOB_STATUS.CLOSED, JOB_STATUS.EXPIRED],
  [JOB_STATUS.HIDDEN]: [JOB_STATUS.ACTIVE, JOB_STATUS.CLOSED, JOB_STATUS.EXPIRED],
  [JOB_STATUS.CLOSED]: [],
  [JOB_STATUS.EXPIRED]: [],
})

const APPLICATION_TRANSITIONS = Object.freeze({
  [APPLICATION_STATUS.RECEIVED]: [APPLICATION_STATUS.REVIEWING, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.REVIEWING]: [APPLICATION_STATUS.INTERVIEW, APPLICATION_STATUS.OFFER, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.INTERVIEW]: [APPLICATION_STATUS.OFFER, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.OFFER]: [],
  [APPLICATION_STATUS.REJECTED]: [],
})

const assertJobTransition = (from, to) => {
  if (!JOB_TRANSITIONS[from]?.includes(to)) throw new ApiError(422, 'Trạng thái tin tuyển dụng không hợp lệ.', 'INVALID_JOB_STATUS_TRANSITION')
}

const assertApplicationTransition = (from, to) => {
  if (!APPLICATION_TRANSITIONS[from]?.includes(to)) throw new ApiError(422, 'Trạng thái hồ sơ ứng tuyển không hợp lệ.', 'INVALID_APPLICATION_STATUS_TRANSITION')
}

module.exports = { APPLICATION_STATUS, JOB_STATUS, assertApplicationTransition, assertJobTransition }
